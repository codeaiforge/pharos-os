#!/usr/bin/env python3
"""Writes crates/pharos-infer/src/unicode.rs: the Unicode letter (\\p{L})
and number (\\p{N}) ranges the Qwen2 pre-tokenizer needs (#84), from the
Python standard library's Unicode database. Run it again only to move to
another Unicode version; the output is committed and reviewed.

Usage: python3 scripts/gen-unicode-tables.py
"""

import pathlib
import unicodedata

OUT = pathlib.Path(__file__).resolve().parent.parent / "crates/pharos-infer/src/unicode.rs"


def ranges(prefix):
    out, start = [], None
    for c in range(0x110000):
        hit = not 0xD800 <= c <= 0xDFFF and unicodedata.category(chr(c)).startswith(prefix)
        if hit and start is None:
            start = c
        elif not hit and start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name, rows):
    lines = [f"pub const {name}: [(u32, u32); {len(rows)}] = ["]
    lines += [f"    (0x{a:x}, 0x{b:x})," for a, b in rows]
    lines.append("];")
    return "\n".join(lines)


def main():
    text = f"""//! Unicode letter and number ranges for the Qwen2 pre-tokenizer (#84):
//! General_Category L* and N*, Unicode {unicodedata.unidata_version}.
//! Generated by `scripts/gen-unicode-tables.py`; do not edit by hand.

/// `\\p{{L}}`: inclusive ranges, sorted, not overlapping.
#[rustfmt::skip]
{table("LETTERS", ranges("L"))}

/// `\\p{{N}}`: inclusive ranges, sorted, not overlapping.
#[rustfmt::skip]
{table("NUMBERS", ranges("N"))}
"""
    OUT.write_text(text)
    print(f"wrote {OUT} (Unicode {unicodedata.unidata_version})")


if __name__ == "__main__":
    main()
